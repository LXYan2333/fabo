"""Generate the QUICK VSR port from the supplied decimal coefficients.

No refitting, changed boundaries, or approximation search. The F0 section-header
correction is explicit and checked against JCP 164, 154111 (2026), Table II.
"""
import argparse
import hashlib
from pathlib import Path
import re


def coefficients(root):
    result = {}
    key = None
    for line in (root/'coefficients.txt').read_text().splitlines():
        if not line.strip():
            continue
        match = re.fullmatch(r'F(\d+) (numerator|denominator)', line)
        if match:
            key = (int(match[1]), match[2])
            if key in result:
                raise ValueError('duplicate coefficient block')
            result[key] = []
        elif key is None:
            raise ValueError('coefficient before heading')
        else:
            result[key].append(float(line))
    if set(result) != {(n,p) for n in range(33) for p in ('numerator','denominator')}:
        raise ValueError('expected supplied orders 0..32')
    a,b=result[0,'numerator'],result[0,'denominator']
    if len(a)!=8 or len(b)!=9 or a[-1]!=float('4.59649054199579770E+11'):
        raise ValueError('F0 transcription correction context changed')
    b.insert(0,a.pop())
    return result


def source_constants(root):
    text=(root/'minimax.c').read_text()
    values={k:float(v) for k,v in re.findall(r'\b([abcd][0-9]+)\s*=\s*([+\-0-9.Ee]+)',text)}
    ctext=(root/'constants.h').read_text()
    bounds={k:float(v) for k,v in re.findall(r'\b(halfsqrtpi|x_0|x_1)\s*=\s*([+\-0-9.Ee]+)',ctext)}
    if len(values)!=30 or set(bounds)!={'halfsqrtpi','x_0','x_1'}:
        raise ValueError('supplied rational/source constant layout changed')
    return values,bounds


def horner(name, values):
    lines=[f'    double {name} = {values[-1].hex()};']
    for i,c in enumerate(reversed(values[:-1])):
        product = 'x' if i==0 and values[-1]==1.0 else f'{name} * x'
        lines.append(f'    {name} = {product} + {c.hex()};')
    return lines


def generate(root):
    table=coefficients(root)
    source,bounds=source_constants(root)
    # The supplied executable specializes k=12. Cross-check its complete lower
    # seed against the independent coefficient file before emitting any code.
    for letter,part in [('a','numerator'),('b','denominator')]:
        expected=[source[f'{letter}{i}'] for i in range(9)]
        if letter=='b': expected.append(1.0)
        if table[12,part]!=expected:
            raise ValueError('supplied F12 coefficients disagree with minimax.c')
    lines=['// Generated by vsr_generate.py; do not edit. Decimal inputs round once to binary64.',
           '// VSR: J. Chem. Phys. 164, 154111 (2026), DOI 10.1063/5.0316073.',
           '#ifndef FABO_VSR_COEFFICIENTS_H','#define FABO_VSR_COEFFICIENTS_H']
    for name in ('coefficients.txt','minimax.c','constants.h'):
        lines.append('// '+name+' SHA-256: '+hashlib.sha256((root/name).read_bytes()).hexdigest())
    for name,value in bounds.items():
        lines.append(f'static constexpr double fabo_vsr_{name} = {value.hex()};')
    lines += ['__device__ static __forceinline__ double FaboVsrSeed(int maximum, double x) {',
              '  switch (maximum) {']
    for n in range(13):
        lines += [f'  case {n}: {{',*horner('p',table[n,'numerator']),
                  *horner('q',table[n,'denominator']),'    return p / q;','  }']
    lines += ['  default: return __longlong_as_double(0x7ff8000000000000ULL);', '  }','}',
              '__device__ static __forceinline__ double FaboVsrMiddle(double x) {',
              *horner('p',[source[f'c{i}'] for i in range(6)]),
              *horner('q',[source[f'd{i}'] for i in range(6)]+[1.0]),'    return p / q;','}',
              '#endif','']
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--source',type=Path,default=Path(__file__).resolve().parents[2]/'third_party/vsr/supplied')
    parser.add_argument('--output',type=Path,default=Path(__file__).with_name('vsr_coefficients.h'))
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    text=generate(args.source)
    if args.check:
        if args.output.read_text()!=text: raise ValueError('stale VSR generated header')
    else:
        args.output.write_text(text)


if __name__=='__main__': main()
