"""Mechanical stride-only adaptation of the pinned GANSU Boys implementation."""
import argparse
from pathlib import Path
import re


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError('GANSU patch context changed: '+old)
    return text.replace(old, new, 1)


def generate(upstream):
    text = (upstream/'include/boys.hpp').read_text()
    parameters = (upstream/'include/parameters.h').read_text()
    constants = dict(re.findall(r'^#define (\w+) (\S+)', parameters, re.M))
    names = ('A_TR','B_TR','A_RS','B_RS','AA','BB','CC','DD',
             'LUT_N_RANGE','LUT_XI_RANGE','LUT_XI_INTERVAL','LUT_NUM_XI','LUT_K_MAX')
    declarations = '\n'.join(f'inline constexpr auto {n} = {constants[n]};' for n in names)
    text = replace_once(text, '#include "parameters.h"', '#include <cstddef>')
    text = text.replace('BOYS_CUH', 'FABO_GANSU_BOYS_H')
    text = text.replace('namespace gansu::gpu{', 'namespace fabo_gansu {\n'+declarations)
    text = text.replace('namespace gansu::gpu', 'namespace fabo_gansu')
    # Keep the original operations, loops and branch predicates. Only output
    # addresses change, so QUICK does not need a local array or copy-back pass.
    if text.count('double* boys)') != 4:
        raise ValueError('unexpected GANSU incremental helper signatures')
    text = text.replace('double* boys)', 'double* boys, std::size_t stride)')
    text = text.replace('boys[j]', 'boys[j * stride]').replace('boys[0]', 'boys[0 * stride]')
    text = text.replace('x, boys);', 'x, boys, stride);')
    text = text.replace('x, g_F_xi, boys);', 'x, g_F_xi, boys, stride);')
    return '// Generated by gansu_adapter.py from GANSU v2026.8.10; do not edit.\n'+text+'\n'


def source_for(text, variant):
    if variant != 'gansu':
        return text
    if 'gansu_boys.h' in text:
        raise ValueError('GANSU binding already patched')
    for old, new in (
        ('#define FABO_PROBE_BOYS_H', '#define FABO_PROBE_BOYS_H\n#if FABO_PROBE_VARIANT == 12\n#include "gansu_boys.h"\n#endif'),
        ('#if FABO_PROBE_VARIANT < 5 || FABO_PROBE_VARIANT == 8',
         '#if FABO_PROBE_VARIANT < 5 || FABO_PROBE_VARIANT == 8 || FABO_PROBE_VARIANT == 12'),
        ('#elif FABO_PROBE_VARIANT == 4\n',
         '#elif FABO_PROBE_VARIANT == 12\n    fabo_gansu::getIncrementalBoys(MaxM, X, fabo_gansu_table, YVerticalTemp, gridDim.x * blockDim.x);\n#elif FABO_PROBE_VARIANT == 4\n')):
        text = replace_once(text, old, new)
    return text


def runtime_for(text, variant):
    if variant != 'gansu':
        return text
    if 'fabo_gansu_runtime.h' in text:
        raise ValueError('GANSU runtime already patched')
    text = replace_once(text, 'extern "C" void fabo_probe_sync_() {',
                        '#if FABO_PROBE_VARIANT == 12\n#include "fabo_gansu_runtime.h"\n#endif\nextern "C" void fabo_probe_sync_() {')
    return replace_once(text, 'extern "C" void fabo_probe_init_() {',
                        'extern "C" void fabo_probe_init_() {\n#if FABO_PROBE_VARIANT == 12\n    fabo_gansu_init();\n#endif')


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--upstream', type=Path, default=Path(__file__).resolve().parents[2]/'third_party/gansu/upstream')
    p.add_argument('--output', type=Path, default=Path(__file__).with_name('gansu_boys.h'))
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    text = generate(a.upstream)
    if a.check:
        if a.output.read_text() != text:
            raise ValueError('stale GANSU generated adapter')
    else:
        a.output.write_text(text)


if __name__ == '__main__':
    main()
