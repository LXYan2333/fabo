#!/usr/bin/env python3
"""Generate C++ coefficient tables from the publisher's Appendix D HTML."""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from bs4 import BeautifulSoup


REGION_A_END = "11.899848152108484"
REGION_B_END = "28.989337738820740"
EXPECTED_TABLE_COUNT = 34


def parse_number(cell) -> str | None:
    text = cell.get_text("", strip=True)
    text = re.sub(r"[\s\u2009\u00a0]", "", text).replace("−", "-")
    if not text:
        return None
    match = re.fullmatch(r"([+-]?[0-9]+(?:\.[0-9]+)?)(?:×10([+-]?[0-9]+))?", text)
    if match is None:
        raise ValueError(f"cannot parse coefficient {text!r}")
    mantissa, exponent = match.groups()
    return mantissa if exponent is None else f"{mantissa}e{exponent}"


def parse_table(table) -> tuple[list[str], list[str]]:
    numerator: list[str] = []
    denominator: list[str] = []
    for row in table.select("tbody tr"):
        cells = row.find_all("td", recursive=False)
        if len(cells) == 2:
            numerator_value = parse_number(cells[0])
            denominator_value = parse_number(cells[1])
        elif len(cells) == 1:
            numerator_value = None
            denominator_value = parse_number(cells[0])
        else:
            raise ValueError(f"unexpected table row with {len(cells)} cells")
        if numerator_value is not None:
            numerator.append(numerator_value)
        if denominator_value is None:
            raise ValueError("denominator coefficient is missing")
        denominator.append(denominator_value)
    return numerator, denominator


def array(name: str, values: list[str]) -> str:
    body = ",\n      ".join(values)
    return (
        f"  inline static constexpr std::array<double, {len(values)}> {name} = {{\n"
        f"      {body},\n  }};\n"
    )


def generate(input_path: Path) -> str:
    soup = BeautifulSoup(input_path.read_text(encoding="utf-8"), "html.parser")
    tables = soup.select("table[role=table]")
    if len(tables) != EXPECTED_TABLE_COUNT:
        raise ValueError(f"expected {EXPECTED_TABLE_COUNT} tables, found {len(tables)}")

    page_text = re.sub(r"[\s\u2009\u00a0]", "", soup.get_text())
    for value in (REGION_A_END, REGION_B_END):
        if value not in page_text:
            raise ValueError(f"separation point {value} is missing from the HTML")

    captions = [
        re.sub(r"[\s\u2009\u00a0]", "", table.find_previous(class_="caption").get_text())
        for table in tables
    ]
    if "F0on[x0,x1" not in captions[0]:
        raise ValueError("Table I is not the region-B approximation of F_0")
    for order, caption in enumerate(captions[1:]):
        if f"F{order}on[0,x0" not in caption:
            raise ValueError(f"unexpected caption for region-A order {order}: {caption}")

    parsed = [parse_table(table) for table in tables]
    output = [
        "// Generated by generate_coefficients.py from the publisher's Appendix D HTML.",
        "// The paper specifies 17 significant digits for correctly rounded doubles.",
        "#ifndef FAST_BOYS_BENCHMARK_VIKHAMAR_SANDBERG_REPISKY_COEFFICIENTS_H_",
        "#define FAST_BOYS_BENCHMARK_VIKHAMAR_SANDBERG_REPISKY_COEFFICIENTS_H_",
        "",
        "#include <array>",
        "#include <cstddef>",
        "",
        "namespace fast_boys::benchmark::vikhamar_sandberg_repisky::coefficients {",
        "",
        "// Appendix D, Eqs. (D1) and (D2), for epsilon_tol = 5e-14.",
        f"inline constexpr double kRegionAEnd = {REGION_A_END};",
        f"inline constexpr double kRegionBEnd = {REGION_B_END};",
        "",
        "template <std::size_t Order>",
        "struct RegionA;",
        "",
    ]

    region_b_numerator, region_b_denominator = parsed[0]
    output.extend([
        "struct RegionB {",
        array("numerator", region_b_numerator).rstrip(),
        array("denominator", region_b_denominator).rstrip(),
        "};",
        "",
    ])

    for order, (numerator, denominator) in enumerate(parsed[1:]):
        output.extend([
            "template <>",
            f"struct RegionA<{order}> {{",
            array("numerator", numerator).rstrip(),
            array("denominator", denominator).rstrip(),
            "};",
            "",
        ])

    output.extend([
        "}  // namespace fast_boys::benchmark::vikhamar_sandberg_repisky::coefficients",
        "",
        "#endif  // FAST_BOYS_BENCHMARK_VIKHAMAR_SANDBERG_REPISKY_COEFFICIENTS_H_",
        "",
    ])
    return "\n".join(output)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path, help="saved Appendix D HTML")
    parser.add_argument("output", type=Path, help="generated C++ header")
    arguments = parser.parse_args()
    arguments.output.write_text(generate(arguments.input), encoding="utf-8")


if __name__ == "__main__":
    main()
